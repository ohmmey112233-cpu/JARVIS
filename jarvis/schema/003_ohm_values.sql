-- friday_anchor_date --------------------------------------------------------
-- โอมตอบ: ศุกร์ล่าสุด = สัปดาห์โรงแรม (อยู่เชียงใหม่ ไม่ได้กลับจอมทอง)
-- ศุกร์ล่าสุดที่ผ่านมา ณ วันพฤหัสที่ 20 ส.ค. 2026 = ศุกร์ที่ 14 ส.ค. 2026
--
-- ผลที่ตามมา (ตรวจให้ตรงกับความจริงก่อนเชื่อ):
--   ศ. 14 ส.ค. = hotel   ← anchor
--   ศ. 21 ส.ค. = home    (กลับจอมทอง)
--   ศ. 28 ส.ค. = hotel
--   ศ.  4 ก.ย. = home
UPDATE preferences
   SET value = '2026-08-14:hotel',
       notes = 'ศุกร์ล่าสุดที่ผ่านมา = สัปดาห์โรงแรม (โอมยืนยัน 20 ส.ค. 2026)',
       updated_at = datetime('now')
 WHERE key = 'friday_anchor_date';

-- last_done ของ diode และ eyebrow -------------------------------------------
-- โอมตอบ: ทำครั้งล่าสุดทั้งคู่เมื่อเสาร์ที่ผ่านมา = เสาร์ที่ 15 ส.ค. 2026
--   ไดโอด รอบ 14 วัน → ถึงรอบ 29 ส.ค.
--   คิ้ว   รอบ  7 วัน → ถึงรอบ 22 ส.ค.
UPDATE routines SET last_done = '2026-08-15' WHERE name = 'diode';
