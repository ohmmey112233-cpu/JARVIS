-- =============================================================================
-- 004 — ยืนยันศุกร์รายสัปดาห์ (แทนที่จะเชื่อการสลับล้วนๆ)
-- =============================================================================
-- โอมบอกเองว่า "มันแล้วแต่สถานการณ์ ขอให้ถามทุกสัปดาห์"
--
-- แปลว่าการสลับ home/hotel จาก anchor เป็นแค่ "การคาดเดา" ไม่ใช่ข้อเท็จจริง
-- ตารางนี้เก็บคำตอบจริงของแต่ละศุกร์ทับการคาดเดา
--
-- ทำไมถึงสำคัญกว่าที่คิด (red-team H10):
--   "no-show ซ้ำๆ ทำให้บัญชีโดนแบนเร็วกว่าเรื่องละเมิด ToS ด้วยซ้ำ"
--   ระบบที่ "เดาแล้วจองเลย" อันตรายกว่าระบบที่ "เดาแล้วถามก่อน" มาก
--   → การจองอัตโนมัติจะทำได้เฉพาะศุกร์ที่ยืนยันแล้วเท่านั้น
-- =============================================================================

CREATE TABLE IF NOT EXISTS friday_overrides (
  friday_date TEXT PRIMARY KEY,          -- 'YYYY-MM-DD' ต้องเป็นวันศุกร์ (โค้ดบังคับ)
  state       TEXT NOT NULL,             -- 'home' | 'hotel'
  note        TEXT,                      -- เหตุผล เช่น 'มีงานที่โรงเรียนเสาร์'
  set_at      TEXT NOT NULL DEFAULT (datetime('now')),
  CHECK (state IN ('home', 'hotel'))
);

